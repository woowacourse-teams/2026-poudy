ALTER TABLE ingredient_group ADD COLUMN tag_name VARCHAR(100);

UPDATE ingredient_group SET tag_name = CASE code
    WHEN 'FRAGRANCE_ALLERGENS' THEN '향료'
    WHEN 'DRYING_ALCOHOLS' THEN '건조 알코올'
    WHEN 'HARSH_PRESERVATIVES' THEN '자극성 방부제'
    WHEN 'SULFATES' THEN '설페이트'
    WHEN 'CYCLIC_SILICONES' THEN '실리콘'
    WHEN 'SYNTHETIC_COLORANTS' THEN '합성 색소'
END
WHERE code IN (
    'FRAGRANCE_ALLERGENS', 'DRYING_ALCOHOLS', 'HARSH_PRESERVATIVES',
    'SULFATES', 'CYCLIC_SILICONES', 'SYNTHETIC_COLORANTS'
);
