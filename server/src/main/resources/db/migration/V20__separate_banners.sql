LOCK TABLE curation IN ACCESS EXCLUSIVE MODE;

CREATE TABLE banner (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    slot VARCHAR(20) NOT NULL CHECK (slot IN ('MAIN', 'STRIP')),
    title VARCHAR(200) NOT NULL CHECK (btrim(title) <> ''),
    description TEXT NOT NULL CHECK (btrim(description) <> ''),
    image_url VARCHAR(1000) CHECK (image_url IS NULL OR btrim(image_url) <> ''),
    target JSONB NOT NULL CHECK (jsonb_typeof(target) = 'object'),
    display_order INT NOT NULL CHECK (display_order >= 0),
    visible BOOLEAN NOT NULL,
    created_at TIMESTAMP NOT NULL DEFAULT (now() AT TIME ZONE 'Asia/Seoul'),
    updated_at TIMESTAMP NOT NULL DEFAULT (now() AT TIME ZONE 'Asia/Seoul'),
    CONSTRAINT ck_banner_image CHECK (NOT visible OR image_url IS NOT NULL)
);

CREATE INDEX ix_banner_slot_order ON banner (slot, display_order, id) WHERE visible;

-- SQL로 적재하는 현재 쓰기 경로에서도 큐레이션 참조의 존재를 확인한다.
-- 게시 상태는 조회 시 판정하며, 삭제를 막는 FK 관계는 만들지 않는다.
CREATE FUNCTION require_banner_curation() RETURNS trigger LANGUAGE plpgsql AS $$
BEGIN
    IF NEW.target ->> 'type' = 'CURATION' THEN
        IF jsonb_typeof(NEW.target -> 'curationId') IS DISTINCT FROM 'number'
            OR (NEW.target ->> 'curationId') !~ '^[1-9][0-9]*$' THEN
            RAISE EXCEPTION 'banner curationId must be a positive bigint' USING ERRCODE = '23514';
        END IF;
        IF NOT EXISTS (SELECT 1 FROM curation WHERE id = (NEW.target ->> 'curationId')::bigint) THEN
            RAISE EXCEPTION 'banner curation does not exist' USING ERRCODE = '23503';
        END IF;
    END IF;
    RETURN NEW;
END $$;

CREATE TRIGGER tg_banner_curation BEFORE INSERT OR UPDATE OF target ON banner
    FOR EACH ROW EXECUTE FUNCTION require_banner_curation();

INSERT INTO banner (slot, title, description, image_url, target, display_order, visible, created_at, updated_at)
SELECT 'MAIN', title, description, banner_thumbnail_image_url,
    jsonb_build_object('type', 'CURATION', 'curationId', id),
    row_number() OVER (ORDER BY position) - 1, banner_visible, created_at, updated_at
FROM curation ORDER BY position;

ALTER TABLE curation DROP COLUMN position, DROP COLUMN banner_visible,
    DROP COLUMN banner_thumbnail_image_url;
