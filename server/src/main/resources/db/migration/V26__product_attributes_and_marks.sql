CREATE TABLE attribute (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    code VARCHAR(50) NOT NULL UNIQUE CHECK (code ~ '^[A-Z][A-Z0-9_]*$'),
    name VARCHAR(100) NOT NULL CHECK (name !~ '^[[:space:]]*$'),
    created_at TIMESTAMP NOT NULL DEFAULT (now() AT TIME ZONE 'Asia/Seoul'),
    updated_at TIMESTAMP NOT NULL DEFAULT (now() AT TIME ZONE 'Asia/Seoul')
);

CREATE TABLE category_attribute (
    category_id BIGINT NOT NULL REFERENCES category(id),
    attribute_id BIGINT NOT NULL REFERENCES attribute(id),
    display_order INTEGER NOT NULL DEFAULT 0 CHECK (display_order >= 0),
    created_at TIMESTAMP NOT NULL DEFAULT (now() AT TIME ZONE 'Asia/Seoul'),
    updated_at TIMESTAMP NOT NULL DEFAULT (now() AT TIME ZONE 'Asia/Seoul'),
    PRIMARY KEY (category_id, attribute_id)
);

CREATE TABLE attribute_value (
    attribute_id BIGINT NOT NULL REFERENCES attribute(id),
    value_code VARCHAR(50) NOT NULL CHECK (value_code ~ '^[A-Z][A-Z0-9_]*$'),
    name VARCHAR(100) NOT NULL CHECK (name !~ '^[[:space:]]*$'),
    display_order INTEGER NOT NULL DEFAULT 0 CHECK (display_order >= 0),
    created_at TIMESTAMP NOT NULL DEFAULT (now() AT TIME ZONE 'Asia/Seoul'),
    updated_at TIMESTAMP NOT NULL DEFAULT (now() AT TIME ZONE 'Asia/Seoul'),
    PRIMARY KEY (attribute_id, value_code)
);

CREATE TABLE product_attribute_value (
    product_id BIGINT NOT NULL REFERENCES product(id),
    attribute_id BIGINT NOT NULL,
    value_code VARCHAR(50) NOT NULL,
    created_at TIMESTAMP NOT NULL DEFAULT (now() AT TIME ZONE 'Asia/Seoul'),
    updated_at TIMESTAMP NOT NULL DEFAULT (now() AT TIME ZONE 'Asia/Seoul'),
    PRIMARY KEY (product_id, attribute_id),
    FOREIGN KEY (attribute_id, value_code) REFERENCES attribute_value(attribute_id, value_code)
);

CREATE INDEX ix_product_attribute_value_filter ON product_attribute_value(attribute_id, value_code, product_id);
CREATE INDEX ix_category_attribute_attribute ON category_attribute(attribute_id, category_id);

