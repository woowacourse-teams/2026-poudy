-- 서로 다른 테이블의 적용 범위 검증은 모든 관련 쓰기가 직렬화 대상이어야 안전하다.
CREATE FUNCTION require_attribute_write_isolation() RETURNS trigger LANGUAGE plpgsql AS $$
BEGIN
    IF current_setting('transaction_isolation') <> 'serializable' THEN
        RAISE EXCEPTION '속성값·적용 범위 변경은 SERIALIZABLE 트랜잭션에서 실행한다.' USING ERRCODE = '23514';
    END IF;
    IF TG_OP = 'DELETE' THEN RETURN OLD; END IF;
    RETURN NEW;
END $$;

CREATE TRIGGER tg_category_attribute_isolation BEFORE INSERT OR UPDATE OR DELETE ON category_attribute
    FOR EACH ROW EXECUTE FUNCTION require_attribute_write_isolation();
CREATE TRIGGER tg_product_attribute_value_isolation BEFORE INSERT OR UPDATE OR DELETE ON product_attribute_value
    FOR EACH ROW EXECUTE FUNCTION require_attribute_write_isolation();
CREATE TRIGGER tg_product_category_attribute_isolation BEFORE UPDATE OF category_id ON product
    FOR EACH ROW WHEN (OLD.category_id IS DISTINCT FROM NEW.category_id)
    EXECUTE FUNCTION require_attribute_write_isolation();
CREATE TRIGGER tg_category_parent_attribute_isolation BEFORE UPDATE OF parent_id, depth ON category
    FOR EACH ROW WHEN (OLD.parent_id IS DISTINCT FROM NEW.parent_id OR OLD.depth IS DISTINCT FROM NEW.depth)
    EXECUTE FUNCTION require_attribute_write_isolation();

CREATE FUNCTION validate_product_attribute_scope() RETURNS trigger LANGUAGE plpgsql AS $$
DECLARE
    affected_product BIGINT;
BEGIN
    IF TG_TABLE_NAME = 'product' THEN affected_product := NEW.id; END IF;
    IF TG_TABLE_NAME = 'product_attribute_value' THEN affected_product := COALESCE(NEW.product_id, OLD.product_id); END IF;
    IF EXISTS (SELECT 1 FROM category_attribute ca JOIN category c ON c.id = ca.category_id WHERE c.depth <> 0) THEN
        RAISE EXCEPTION '속성 적용 카테고리는 대분류여야 한다.' USING ERRCODE = '23514';
    END IF;
    IF EXISTS (
        SELECT 1 FROM product_attribute_value pav
        JOIN product p ON p.id = pav.product_id JOIN category c ON c.id = p.category_id
        LEFT JOIN category_attribute ca ON ca.category_id = c.parent_id AND ca.attribute_id = pav.attribute_id
        WHERE (affected_product IS NULL OR p.id = affected_product) AND (c.depth <> 1 OR ca.attribute_id IS NULL)
    ) THEN
        RAISE EXCEPTION '제품 카테고리에 허용되지 않은 속성값이다.' USING ERRCODE = '23514';
    END IF;
    RETURN NULL;
END $$;

CREATE CONSTRAINT TRIGGER tg_product_attribute_scope AFTER INSERT OR UPDATE OR DELETE ON product_attribute_value
    DEFERRABLE INITIALLY DEFERRED FOR EACH ROW EXECUTE FUNCTION validate_product_attribute_scope();
CREATE CONSTRAINT TRIGGER tg_category_attribute_scope AFTER INSERT OR UPDATE OR DELETE ON category_attribute
    DEFERRABLE INITIALLY DEFERRED FOR EACH ROW EXECUTE FUNCTION validate_product_attribute_scope();
CREATE CONSTRAINT TRIGGER tg_product_category_attribute_scope AFTER UPDATE OF category_id ON product
    DEFERRABLE INITIALLY DEFERRED FOR EACH ROW EXECUTE FUNCTION validate_product_attribute_scope();
CREATE CONSTRAINT TRIGGER tg_category_parent_attribute_scope AFTER UPDATE OF parent_id, depth ON category
    DEFERRABLE INITIALLY DEFERRED FOR EACH ROW EXECUTE FUNCTION validate_product_attribute_scope();

CREATE FUNCTION reject_attribute_truncate() RETURNS trigger LANGUAGE plpgsql AS $$
BEGIN
    RAISE EXCEPTION '속성 연결은 DELETE로 정리한다.' USING ERRCODE = '23514';
END $$;
CREATE TRIGGER tg_category_attribute_reject_truncate BEFORE TRUNCATE ON category_attribute
    EXECUTE FUNCTION reject_attribute_truncate();
CREATE TRIGGER tg_product_attribute_reject_truncate BEFORE TRUNCATE ON product_attribute_value
    EXECUTE FUNCTION reject_attribute_truncate();

CREATE FUNCTION touch_attribute_updated_at() RETURNS trigger LANGUAGE plpgsql AS $$
BEGIN
    NEW.updated_at := (clock_timestamp() AT TIME ZONE 'Asia/Seoul');
    RETURN NEW;
END $$;
CREATE TRIGGER tg_attribute_updated_at BEFORE UPDATE ON attribute
    FOR EACH ROW EXECUTE FUNCTION touch_attribute_updated_at();
CREATE TRIGGER tg_attribute_value_updated_at BEFORE UPDATE ON attribute_value
    FOR EACH ROW EXECUTE FUNCTION touch_attribute_updated_at();
CREATE TRIGGER tg_category_attribute_updated_at BEFORE UPDATE ON category_attribute
    FOR EACH ROW EXECUTE FUNCTION touch_attribute_updated_at();
CREATE TRIGGER tg_product_attribute_value_updated_at BEFORE UPDATE ON product_attribute_value
    FOR EACH ROW EXECUTE FUNCTION touch_attribute_updated_at();

CREATE FUNCTION touch_attribute_products() RETURNS trigger LANGUAGE plpgsql AS $$
BEGIN
    IF TG_TABLE_NAME = 'product_attribute_value' THEN
        UPDATE product SET updated_at = (clock_timestamp() AT TIME ZONE 'Asia/Seoul')
        WHERE id IN (COALESCE(NEW.product_id, OLD.product_id), CASE WHEN TG_OP = 'UPDATE' THEN OLD.product_id END);
    ELSE
        UPDATE product SET updated_at = (clock_timestamp() AT TIME ZONE 'Asia/Seoul')
        WHERE id IN (SELECT product_id FROM product_attribute_value
            WHERE attribute_id = NEW.attribute_id AND value_code = NEW.value_code);
    END IF;
    RETURN NULL;
END $$;
CREATE TRIGGER tg_product_attribute_touch_product AFTER INSERT OR UPDATE OR DELETE ON product_attribute_value
    FOR EACH ROW EXECUTE FUNCTION touch_attribute_products();
CREATE TRIGGER tg_attribute_value_touch_products AFTER UPDATE OF name ON attribute_value
    FOR EACH ROW WHEN (OLD.name IS DISTINCT FROM NEW.name) EXECUTE FUNCTION touch_attribute_products();
