CREATE TEMPORARY TABLE skin_type_target ON COMMIT DROP AS
SELECT p.id AS product_id, s.code AS skin_type_code
FROM product p
JOIN skin_type_import i ON i.product_id = p.id
CROSS JOIN LATERAL (VALUES ('DRY', i.dry), ('OILY', i.oily), ('COMBINATION', i.combination)) AS s(code, flag)
WHERE s.flag;

UPDATE product p
SET updated_at = (now() AT TIME ZONE 'Asia/Seoul')
WHERE p.is_sensitive_skin <> COALESCE((SELECT i.sensitive FROM skin_type_import i WHERE i.product_id = p.id), false)
   OR EXISTS (
       (SELECT s.skin_type_code FROM product_skin_type s WHERE s.product_id = p.id
        EXCEPT
        SELECT t.skin_type_code FROM skin_type_target t WHERE t.product_id = p.id)
       UNION ALL
       (SELECT t.skin_type_code FROM skin_type_target t WHERE t.product_id = p.id
        EXCEPT
        SELECT s.skin_type_code FROM product_skin_type s WHERE s.product_id = p.id)
   );

UPDATE product p
SET is_sensitive_skin = COALESCE((SELECT i.sensitive FROM skin_type_import i WHERE i.product_id = p.id), false)
WHERE p.is_sensitive_skin <> COALESCE((SELECT i.sensitive FROM skin_type_import i WHERE i.product_id = p.id), false);

DELETE FROM product_skin_type;

INSERT INTO product_skin_type (product_id, skin_type_code)
SELECT product_id, skin_type_code FROM skin_type_target;
