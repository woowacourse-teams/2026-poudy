/**
 * 닫는 따옴표(’)와 바로 뒤에 붙은 조사·글자를 단어 결합자(U+2060)로 잇는다.
 *
 * 한국어 줄바꿈(keep-all)에서도 브라우저는 닫는 따옴표 뒤에서 줄을 넘길 수 있어, 글자를 키우면 '‘세라마이드’' / '에'처럼
 * 조사만 다음 줄로 떨어진다. 결합자는 폭이 없고 낭독기는 읽지 않는다. 안내 줄, 토스트, 빈 상태가 화면에 그리는 문구에 쓰고,
 * client 는 관리자가 쓴 긴 글(공지 본문)과 직접 그린 결과 없음 문구에 쓴다. 이미 이은 문구에 다시 써도 결합자를 겹쳐 넣지 않는다.
 */
export const keepQuoteWithParticle = (text: string): string => text.replace(/’(?=[^\s’\u2060])/g, "’\u2060");
