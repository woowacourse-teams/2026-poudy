/**
 * 닫는 따옴표(’)와 바로 뒤에 붙은 조사·글자를 단어 결합자(U+2060)로 잇는다. 패키지 안에서만 쓴다.
 *
 * 한국어 줄바꿈(keep-all)에서도 브라우저는 닫는 따옴표 뒤에서 줄을 넘길 수 있어, 글자를 키우면 '‘세라마이드’' / '에'처럼
 * 조사만 다음 줄로 떨어진다. 결합자는 폭이 없고 낭독기는 읽지 않는다. 안내 줄과 토스트가 화면에 그리는 문구에 쓴다.
 */
export const keepQuoteWithParticle = (text: string): string => text.replace(/’(?=[^\s’])/g, "’\u2060");
